import frappe

from . import QA_ROLE, QA_USER
from .fixtures import ensure

ROLES = (
    "System Manager", "Accounts Manager", "Sales Manager", "Purchase Manager",
    "Stock Manager", "Manufacturing Manager", "Projects Manager",
    "Sales Master Manager", "Purchase Master Manager", "Item Manager",
)


def ensure_executor():
    ensure("Role", QA_ROLE, {"role_name": QA_ROLE, "desk_access": 1, "is_custom": 1})
    existing = frappe.db.exists("User", QA_USER)
    if existing:
        user = frappe.get_doc("User", QA_USER)
        if QA_ROLE not in {row.role for row in user.roles}:
            return [f"{QA_USER} already exists without {QA_ROLE}; it was not modified."]
        if not user.enabled or not user.get("enable_api_access"):
            return [f"Enable {QA_USER} as a dedicated API user before preparing it."]
    else:
        user = frappe.get_doc({
            "doctype": "User", "email": QA_USER, "first_name": "Release QA",
            "enabled": 1, "user_type": "System User", "enable_api_access": 1,
            "send_welcome_email": 0, "roles": [{"role": QA_ROLE}],
        })
    assigned = {row.role for row in user.roles}
    for role in ROLES:
        if role not in assigned and frappe.db.exists("Role", {"name": role, "disabled": 0}):
            user.append("roles", {"role": role})
    frappe.db.savepoint("qa_executor")
    try:
        user.save()
    except frappe.ValidationError:
        frappe.db.rollback(save_point="qa_executor")
        return [f"Could not save {QA_USER}. Check API quota and user validation in the console messages."]
    # Credentials are generated by the operator; repeated preparation must never rotate them.
    return []
